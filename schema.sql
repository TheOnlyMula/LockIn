-- schema PUBLIC

create table public."FocusSession" (
  id bigint generated by default as identity not null,
  "createdAt" timestamp with time zone not null default now(),
  "userID" uuid not null default gen_random_uuid (),
  duration bigint not null,
  category text not null default 'uncategorised'::text,
  "categoryIcon" text not null default 'tag'::text,
  constraint FocusSession_pkey primary key (id),
  constraint FocusSession_userID_fkey foreign KEY ("userID") references auth.users (id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create table public."Relationship" (
  "requesterID" uuid not null default gen_random_uuid (),
  "addresseeID" uuid not null default gen_random_uuid (),
  status public.relationshipStatus not null default 'pending'::"relationshipStatus",
  "createdAt" timestamp with time zone not null default now(),
  constraint Relationship_pkey primary key ("requesterID", "addresseeID"),
  constraint Relationship_addresseeID_fkey foreign KEY ("addresseeID") references auth.users (id) on update CASCADE on delete CASCADE,
  constraint Relationship_requesterID_fkey foreign KEY ("requesterID") references auth.users (id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create table public."Category" (
  "userID" uuid not null default gen_random_uuid (),
  name text not null,
  "categoryIcon" text null,
  constraint Category_pkey primary key ("userID", name),
  constraint Category_userID_fkey foreign KEY ("userID") references auth.users (id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

-- ============================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ============================================================

/*
RLS is ENABLED on all user-owned tables.
All access is restricted to the authenticated user whose auth.uid()
matches the row's "userID" column.

Roles:
- authenticated

Tables with RLS enabled:
- Category
- FocusSession
- Relationship
*/

-- ============================================================
-- CATEGORY POLICIES
-- ============================================================

-- SELECT: Users can read only their own categories
create policy "Enable select access for users based on userID"
on public."Category"
for select
to authenticated
using (auth.uid() = "userID");

-- INSERT: Users can create categories only for themselves
create policy "Enable insert access for users based on userID"
on public."Category"
for insert
to authenticated
with check (auth.uid() = "userID");

-- UPDATE: Users can update only their own categories
create policy "Enable update access for users based on userID"
on public."Category"
for update
to authenticated
using (auth.uid() = "userID")
with check (auth.uid() = "userID");

-- DELETE: Users can delete only their own categories
create policy "Enable delete access for users based on userID"
on public."Category"
for delete
to authenticated
using (auth.uid() = "userID");

